# -*- coding: utf-8 -*-

"""
L4: install and test a project generated by test-template, then build a
wheel of every other one, so a value that breaks packaging (e.g. an invalid
license expression) is caught too.

- ``TRIAL_PRESET`` (``cctpl/pair.py``) is None: install and test the
  default-value project.
- Otherwise only the ``TRIAL_PRESET`` project (``output/presets/<name>/``) can
  install its dependencies; install and test it, and build a wheel of the
  default-value project.
- Build a wheel of every choice-coverage project (``output/choices/``).

Uses ``INSTALL_COMMAND`` / ``TEST_COMMAND`` from ``cctpl/pair.py`` directly,
never mise (06-verification.md, "Secrets"). There is no uv.lock (it is
excluded from the template), so dependencies resolve fresh, as they will for
a new user.

Exits 1 if installation, any test, or any build fails.
"""

import json
from pathlib import Path

import cctpl


def _find_project(dir_parent: Path) -> Path:
    cctpl.require_dir(dir_parent, "mise run test-template")
    projects = [
        p
        for p in dir_parent.iterdir()
        if p.is_dir() and p.name not in ("choices", "presets")
    ]
    if len(projects) != 1:
        raise cctpl.TaskError(
            f"expected one project in {dir_parent}, found "
            f"{[p.name for p in projects]}. Run 'mise run test-template' first."
        )
    return projects[0]


def main() -> int:
    variables = json.loads(
        (cctpl.dir_template / "cookiecutter.json").read_text(encoding="utf-8")
    )
    dir_default = _find_project(cctpl.dir_output)
    wheels = []

    if cctpl.TRIAL_PRESET is None:
        dir_tested = dir_default
        python = variables[cctpl.PYTHON_VERSION_VARIABLE]
    else:
        dir_tested = _find_project(cctpl.dir_output / "presets" / cctpl.TRIAL_PRESET)
        overrides = cctpl.load_presets()[cctpl.TRIAL_PRESET]
        python = cctpl.apply_preset(variables, overrides)[cctpl.PYTHON_VERSION_VARIABLE]
        wheels.append(dir_default)
    if not cctpl.run_project_tests(dir_tested, python):
        return 1
    print(f"OK: generated project installs and its tests pass ({dir_tested}).")

    dir_choices = cctpl.dir_output / "choices"
    if dir_choices.is_dir():
        wheels.extend(sorted(dir_choices.glob("*/*/")))
    failed = [
        str(d.relative_to(cctpl.dir_output))
        for d in wheels
        if not cctpl.build_wheel(d, variables[cctpl.PYTHON_VERSION_VARIABLE])
    ]
    if failed:
        print(f"FAILED: wheel build failed for {', '.join(failed)}")
        return 1
    print(f"OK: {len(wheels)} other generated project(s) build a wheel.")
    return 0


if __name__ == "__main__":
    cctpl.run_task(main)
